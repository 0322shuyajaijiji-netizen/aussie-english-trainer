import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const text=fs.readFileSync(path.join(root,'phrases.json'),'utf8');
const data=JSON.parse(text);
const original=JSON.parse(fs.readFileSync(path.join(root,'original/phrases.json'),'utf8'));
if(data.length<original.length||new Set(data.map(p=>p.id)).size!==data.length)throw Error('一意な教材IDが必要です');
if(JSON.stringify(data.slice(0,original.length))!==JSON.stringify(original))throw Error('元教材129件を無変更で保持してください');
for(const p of data) if(!p.en||!p.ja||!p.category||!Array.isArray(p.dialogue)) throw Error('教材の必須項目がありません');
fs.writeFileSync(path.join(root,'phrases.js'),'// 自動生成: scripts/build-data.mjs（編集は phrases.json へ）\nwindow.PHRASES = '+JSON.stringify(data,null,2)+';\n');
console.log(`${data.length}フレーズの配信用データを生成しました`);
